function normalizeChannelName(name) {
  return (name || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
}

const normalizedChannelLogos = Object.fromEntries(
  Object.entries(channelLogos).map(([key, value]) => [
    normalizeChannelName(key),
    value,
  ]),
);

// Resolves the best logo available for a channel object coming from the
// Astra/Xtream APIs: curated map first, then whatever the API itself sent.
export function getChannelLogo(channel) {
  if (!channel) return null;

  return (
    normalizedChannelLogos[normalizeChannelName(channel.name)] ||
    channel.logo ||
    channel.icon ||
    null
  );
}
